def preview(body_size):
    """Shared rectangles and A4 masks; Source Han approximates LVGL glyph placement."""
    im = Image.new('RGB',(600,1024),color(LAYOUT['background']))
    d = ImageDraw.Draw(im)
    for item in LAYOUT['items']:
        x,y,w,h=item.get('box28',item['box']) if body_size==28 else item['box']
        if item['kind'] in ['panel','button']:
            d.rounded_rectangle((x,y,x+w-1,y+h-1),radius=item.get('radius',0),fill=color(item['color']),
                                outline=color(item['border']) if item.get('border') else None)
        elif item['kind']=='image':
            resource=item['resource']
            if resource=='native':
                logo=Image.open(ROOT/'assets/brand/native-icon-64.png').convert('RGBA')
                im.paste(logo,(x,y),logo)
            else:
                mask=ART[resource].resize((w,h),Image.Resampling.LANCZOS)
                im.paste(color(item['color']),(x,y,x+w,y+h),mask)
        elif item['kind']=='wave':
            for i,(wh,wc) in enumerate(zip(LAYOUT['wave_heights'],LAYOUT['wave_colors'])):
                left=x+i*20;top=y+(h-wh)//2
                d.rounded_rectangle((left,top,left+9,top+wh-1),radius=5,fill=color(wc))
        elif item['kind']=='label':
            role=item.get('font','body')
            size=28 if role=='heading' else 14 if role=='latin' else body_size
            f=ImageFont.truetype(str(FALLBACK_FONT if role=='latin' else NORMAL_FONT),size)
            text=item['text'];length=d.textlength(text,font=f)
            rows=['']
            for char in text:
                if d.textlength(rows[-1]+char,font=f)>w and rows[-1]:rows.append('')
                rows[-1]+=char
            align=item.get('align','left')
            # Real SD fonts have 27/54 line-height; this is a layout approximation.
            lh=54 if size==28 else 27
            assert len(rows)*lh<=h,(body_size,item['id'],len(rows)*lh,h)
            for n,row in enumerate(rows):
                length=d.textlength(row,font=f)
                tx=x+(w-length)/2 if align=='center' else x+w-length if align=='right' else x
                d.text((round(tx),y+(h-len(rows)*lh)//2+(lh-size)//2+n*lh),row,font=f,fill=color(item['color']),anchor='lt')
        assert x>=0 and y>=0 and x+w<=600 and y+h<=1024,item['id']
    im.save(ASSETS/f'layout-preview-{body_size}.png')


