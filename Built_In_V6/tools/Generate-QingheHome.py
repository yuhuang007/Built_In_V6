def packed_a4(im):
    # LVGL A4 is row-aligned; high nibble is the left pixel.
    out = bytearray()
    for y in range(im.height):
        for x in range(0,im.width,2):
            a = round(im.getpixel((x,y))*15/255)
            b = round(im.getpixel((x+1,y))*15/255) if x+1<im.width else 0
            out.append((a<<4)|b)
    return out


