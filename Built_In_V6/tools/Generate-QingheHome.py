def icon(name):
    scale = 4
    im = Image.new("L", (24*scale, 24*scale))
    d = ImageDraw.Draw(im)
    def points(p): return [(int(x*scale), int(y*scale)) for x, y in p]
    def line(p): d.line(points(p), fill=255, width=6, joint="curve")
    def rect(p, radius=0):
        d.rounded_rectangle(tuple(int(v*scale) for v in p), radius=radius*scale, outline=255, width=6)
    def ellipse(p): d.ellipse(tuple(int(v*scale) for v in p), outline=255, width=6)
    if name == "arrow":
        line([(5,19),(19,5)]); line([(10,5),(19,5),(19,14)])
    elif name == "mic":
        rect((9,2,15,14),3)
        d.arc((6*scale,6*scale,18*scale,18*scale),0,180,fill=255,width=6)
        line([(6,9),(6,12)]); line([(18,9),(18,12)])
        line([(12,18),(12,22)]); line([(9,22),(15,22)])
    elif name == "document":
        rect((5,2,19,22)); line([(8,7),(16,7)]);line([(8,12),(16,12)]);line([(8,17),(13,17)])
    elif name == "camera":
        line([(2,7),(7,7),(9,3),(15,3),(17,7),(22,7),(22,21),(2,21),(2,7)])
        ellipse((7,9,17,19))
    elif name == "settings":
        line([(2,7),(22,7)]);line([(2,17),(22,17)])
        # Erase the line under each outlined knob.
        d.ellipse((5*scale,3*scale,13*scale,11*scale),fill=0)
        d.ellipse((12*scale,13*scale,20*scale,21*scale),fill=0)
        ellipse((5,3,13,11));ellipse((12,13,20,21))
    elif name == "keyboard":
        rect((1,4,23,20),2)
        for y in [8,12]:
            for x in [5,10,15,20]: line([(x,y),(x+.5,y)])
        line([(6,16),(18,16)])
    return im.resize((24,24),Image.Resampling.LANCZOS)


