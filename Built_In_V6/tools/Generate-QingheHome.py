    lines.append(f'}};\nconst lv_image_dsc_t qh_home_{name} = {{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A4,.w={im.width},.h={im.height},.stride={(im.width+1)//2}}},.data_size=sizeof({name}_data),.data={name}_data}};\n')
    header.append(f'extern const lv_image_dsc_t qh_home_{name};\n')
