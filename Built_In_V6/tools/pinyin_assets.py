"""Generate public, content-pinned firmware and transfer metadata."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate():
    asset = ROOT / "assets/pinyin/P4PYV1.DAT"
    data = asset.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    manifest = {"upstream": "pkg-ime/libgooglepinyin", "commit": "4a5016ac35ca5f1db4b56eadcf04ee47f00200f0",
                "abi": "32-bit-little-endian", "personal_learning": False,
                "files": [{"name": asset.name, "bytes": len(data), "sha256": digest}]}
    (asset.parent / "pinyin-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="ascii")
    header = ('/* Generated by tools/pinyin_assets.py. */\n#pragma once\n'
              f'#define PINYIN_ASSET_BYTES {len(data)}u\n'
              f'#define PINYIN_ASSET_SHA256 "{digest}"\n')
    (ROOT / "firmware/p4_main/main/pinyin_asset_meta.h").write_text(header, encoding="ascii")
    print(f"pinyin_asset_bytes={len(data)} sha256={digest}")

if __name__ == "__main__":
    generate()
