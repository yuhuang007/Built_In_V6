/* Reproducible binary font generation. Uses the E:-local lv_font_conv@1.5.3
 * and fonts bundled with the pinned LVGL component; never installs tools. */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const {spawnSync} = require('child_process');
const root = path.resolve(__dirname, '..');
const converterRoot = path.join(root, '.font-tools/node_modules/lv_font_conv');
const opentype = require(path.join(converterRoot, 'node_modules/opentype.js'));
const base = path.join(root, 'firmware/p4_main/managed_components/lvgl__lvgl/scripts/generators/built_in_font');
const primaryPath = path.join(base, 'SourceHanSansSC-Normal.otf');
const fallbackPath = path.join(base, 'DejaVuSans.ttf');
function loadCmap(file) {
  const buffer = fs.readFileSync(file);
  return opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength)).tables.cmap.glyphIndexMap;
}
function ranges(codes) {
  const output = [];
  for (let i = 0; i < codes.length; ++i) {
    let start = codes[i], end = start;
    while (codes[i + 1] === end + 1) end = codes[++i];
    output.push('0x' + start.toString(16) + (start === end ? '' : '-0x' + end.toString(16)));
  }
  return output.join(',');
}
const blocks = [
  [0x20,0x7e], [0xa0,0x24f], [0x370,0x3ff],
  [0x2000,0x206f], [0x20a0,0x20cf], [0x2100,0x214f],
  [0x2190,0x21ff], [0x2200,0x22ff], [0x2300,0x23ff],
  [0x3000,0x303f], [0x3300,0x33ff], [0x3400,0x4dbf],
  [0x4e00,0x9fff], [0xf900,0xfaff], [0xfe10,0xfe19],
  [0xfe30,0xfe6f], [0xff00,0xffef]
];
const requiredText = '，。！？；：、…—–·“”‘’（）【】《》〈〉「」『』〔〕［］｛｝～％＋－＝／＼＠＃＆＊＄＾＿｀｜＜＞．＂＇℃℉Ωμ№≤≥≠≈√∞±×÷°‰′″€£¥$¢₩₽₹￥←↑→↓↔↕你好语音转文字';
const primaryCmap = loadCmap(primaryPath), fallbackCmap = loadCmap(fallbackPath);
const primary = [], fallback = [], covered = [], unsupported = [];
for (const [start,end] of blocks) for (let cp = start; cp <= end; ++cp) {
  if (primaryCmap[cp]) { primary.push(cp); covered.push(cp); }
  else if (fallbackCmap[cp]) { fallback.push(cp); covered.push(cp); }
  else unsupported.push(cp);
}
const required = [...new Set([...requiredText].map(char => char.codePointAt(0)))];
if (required.some(cp => !covered.includes(cp))) throw new Error('Required glyph missing from source fonts');
const out = path.join(root, 'assets/fonts');
const result = {
  converter: 'lv_font_conv@1.5.3', bpp: 4, compression: 0, kerning: false,
  primary: 'SourceHanSansSC-Normal.otf', fallback: 'DejaVuSans.ttf',
  blocks, glyph_count: covered.length, required,
  covered_ranges: ranges(covered), unsupported_ranges: ranges(unsupported),
  files: []
};
for (const size of [14,28]) {
  const name = `P4Z${size}V2.BIN`;
  const target = path.join(out, name);
  const args = [path.join(converterRoot, 'lv_font_conv.js'),
    '--no-compress', '--no-prefilter', '--no-kerning', '--size', String(size),
    '--bpp', '4', '--format', 'bin', '--font', primaryPath, '-r', ranges(primary),
    '--font', fallbackPath, '-r', ranges(fallback), '-o', target];
  const proc = spawnSync(process.execPath, args, {stdio:'inherit'});
  if (proc.status !== 0) throw new Error('Font conversion failed');
  const data = fs.readFileSync(target);
  const hash = crypto.createHash('sha256').update(data).digest('hex');
  result.files.push({name, size_px:size, bytes:data.length, sha256:hash});
  console.log(`font_px=${size} bytes=${data.length} glyphs=${covered.length} sha256=${hash}`);
}
fs.writeFileSync(path.join(out, 'sd-fonts-v2-manifest.json'), JSON.stringify(result, null, 2) + '\n');
const definitions = ['#pragma once', '/* Generated by tools/Generate-SdFonts.cjs; public asset hashes, no credentials. */'];
for (const entry of result.files) {
  definitions.push(`#define SD_FONT_${entry.size_px}_NAME "${entry.name}"`,
    `#define SD_FONT_${entry.size_px}_BYTES ${entry.bytes}U`,
    `#define SD_FONT_${entry.size_px}_SHA256 "${entry.sha256}"`);
}
fs.writeFileSync(path.join(root, 'firmware/p4_main/main/sd_font_assets.h'), definitions.join('\n') + '\n');
/* Preserve the font-data license alongside the generated SD assets. */
fs.copyFileSync(path.join(base, 'font_license/DejaVuSans/LICENSE'), path.join(out, 'SD-FONTS-DEJAVU-LICENSE.txt'));
