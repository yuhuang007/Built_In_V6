// Run as a Tabbit nodejs program against the local preview server.
// Tests the merged presentation using the existing local simulation behaviours.
const variants = globalThis.variants || ['fusion']; // Run one variant per request (about one minute).
globalThis.browserQA = globalThis.browserQA || [];
globalThis.prototypeErrors = globalThis.prototypeErrors || [];
page.on('pageerror', e => prototypeErrors.push(String(e)));
page.on('console', m => {if(m.type()==='error') prototypeErrors.push(m.text());});
await page.setViewportSize({width:1200,height:1120});
for (const variant of variants) {
  await page.goto(`http://127.0.0.1:8765/index.html?page=transcript`, {waitUntil:'load'});
  const check = (condition,message) => {if(!condition)throw Error(variant+': '+message);};
  const reader = page.locator('#transcript-reader');
  const position = () => reader.evaluate(e=>({top:e.scrollTop,bottom:e.scrollHeight-e.clientHeight-e.scrollTop,height:e.clientHeight}));
  await page.locator('#long-demo').click();
  check((await position()).bottom<=32,'long sample must start at latest');
  await page.locator('#record').click();
  await expect(page.locator('#clear-transcript')).toBeDisabled();
  await page.waitForFunction(()=>document.querySelector('.segment:last-child p').textContent!=='下一站是花园。',null,{polling:100,timeout:6500});
  check((await position()).bottom<=32,'bottom must follow growing result');
  await reader.evaluate(e=>{e.scrollTop=220;});
  await expect(page.locator('#reading-state')).toHaveText('正在阅读上文');
  await expect(page.locator('#latest')).toBeVisible();
  const readingTop=(await position()).top;
  for(let i=0;i<3;i++) {
    await page.locator('#revision-demo').click();
    check(Math.abs((await position()).top-readingTop)<2,'up-reading must survive revision growth/shrink');
  }
  await page.locator('#record').click();
  const beforeCancel = await reader.innerText();
  await page.locator('#clear-transcript').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.locator('#cancel-modal').click();
  check(await reader.innerText()===beforeCancel,'cancel must retain transcript');
  check(Math.abs((await position()).top-readingTop)<2,'cancel must retain reading position');
  await page.locator('#latest').click();
  check((await position()).bottom<=32,'latest must return to bottom');
  await expect(page.locator('#latest')).toBeHidden();
  await page.locator('#clear-transcript').click();
  await page.locator('#confirm-modal').click();
  check(await page.locator('.segment').count()===0,'confirm must clear');
  await page.locator('#draft').fill('清空后继续输入。');
  await page.locator('#send').click();
  await expect(reader).toContainText('清空后继续输入。');
  await page.locator('#record').click();
  await expect(page.locator('#record')).toHaveAttribute('aria-pressed','true');
  await page.locator('#record').click();
  await page.locator('#toggle-keyboard').click();
  for(const key of ['n','i','h','a','o']) await page.locator(`[data-key="${key}"]`).click();
  await expect(page.locator('.candidates')).toBeVisible();
  await page.locator('#candidate-next').click();
  await expect(page.locator('.candidates')).toContainText('拟好');
  await page.locator('#candidate-prev').click();
  await expect(page.locator('.candidates')).toContainText('你好');
  const geometry=await page.evaluate(()=>{
    const r=s=>{const e=document.querySelector(s),b=e.getBoundingClientRect();return {top:b.top,bottom:b.bottom,width:b.width,height:b.height,scrollWidth:e.scrollWidth,clientWidth:e.clientWidth};};
    return {reader:r('.reader'),toolbar:r('.toolbar'),candidate:r('.candidates'),composer:r('.composer'),keyboard:r('.keyboard'),device:r('#device')};
  });
  check(geometry.toolbar.bottom<=geometry.candidate.top+1,'candidate must not overlap recording toolbar');
  check(geometry.reader.height>=100,'keyboard needs usable reading area');
  check(geometry.candidate.bottom<=geometry.composer.top+1,'candidate must float above input');
  check(geometry.composer.scrollWidth<=geometry.composer.clientWidth+1,'input cannot overflow horizontally');
  await page.locator('[data-candidate="你好"]').click();
  await expect(page.locator('#draft')).toHaveValue('你好');
  await page.locator('#language').click();
  await page.locator('[data-key="a"]').click();
  await expect(page.locator('#draft')).toHaveValue('你好a');
  await expect(page.locator('.candidates')).toBeHidden();
  await page.locator('#usb-demo').check();
  await expect(page.locator('.keyboard')).toBeHidden();
  const headerTop=await page.locator('.header').evaluate(e=>e.getBoundingClientRect().top);
  await page.locator('#draft').fill('USB 输入样例');
  await expect(page.locator('.keyboard')).toBeHidden();
  check(await page.locator('.header').evaluate(e=>e.getBoundingClientRect().top)===headerTop,'USB typing must not lift page');
  await page.locator('#failure-demo').check();
  await page.locator('#send').click();
  await expect(page.locator('#draft')).toHaveValue('USB 输入样例');
  await expect(page.locator('.feedback')).toContainText('保留');
  await page.locator('#send').click();
  await expect(page.locator('#draft')).toHaveValue('');
  await page.locator('#route-picker').selectOption('home');
  await page.locator('#hold-talk').click({delay:80});
  await expect(page.locator('#interrupt')).toBeVisible();
  await page.locator('#interrupt').click();
  await expect(page.locator('.feedback')).toContainText('打断');
  await page.locator('#offline-demo').check();
  await page.locator('#draft').fill('离线保留的草稿');
  await page.locator('#send').click();
  await expect(page.locator('#draft')).toHaveValue('离线保留的草稿');
  await page.locator('#offline-demo').uncheck();
  await page.locator('#send').click();
  await expect(page.locator('#interrupt')).toBeVisible();
  await expect(page.locator('#hold-talk')).toBeVisible({timeout:6500});
  await expect(page.locator('#messages')).toContainText('收到，我们可以按这个安排继续。');
  await page.locator('#route-picker').selectOption('camera');
  await page.locator('#pause-camera').click();
  await expect(page.locator('.camera-caption')).toHaveText('预览已暂停');
  await page.locator('#camera-guide').click();
  await expect(page.locator('.camera-subject')).toBeHidden();
  await page.locator('#route-picker').selectOption('settings');
  await page.locator('#font-size').selectOption('32');
  await page.locator('#idle').selectOption('0');
  await page.locator('#brightness').press('Home');
  await page.locator('#brightness').press('ArrowRight');
  await expect(page.locator('#brightness-output')).toHaveText('21%');
  await page.locator('#volume').press('Home');
  await page.locator('#volume').press('ArrowRight');
  await expect(page.locator('#volume-output')).toHaveText('1%');
  await page.locator('#clear-history').click();
  await page.locator('#confirm-modal').click();
  await page.locator('#route-picker').selectOption('home');
  await expect(page.locator('#messages')).toContainText('还没有对话');
  await page.locator('#route-picker').selectOption('wifi');
  await page.locator('[data-network="2"]').click();
  await expect(page.locator('#network-notice')).toContainText('连接失败',{timeout:5000});
  await page.locator('#network-recover').click();
  await page.locator('[data-network="1"]').click();
  await page.locator('#demo-password').fill('demo1234');
  await page.locator('#confirm-modal').click();
  await expect(page.locator('#network-notice')).toContainText('已连接 演示网络 · 书房',{timeout:5000});
  await page.locator('#route-picker').selectOption('settings');
  await page.locator('#font-size').selectOption('28');
  await page.locator('#route-picker').selectOption('transcript');
  await page.locator('#long-demo').click();
  await reader.evaluate(e=>{e.scrollTop=220;});
  await expect(page.locator('#latest')).toBeVisible();
  browserQA.push({variant,passed:true,logicalSize:{width:600,height:1024},geometry});
}
return {results:browserQA,errors:prototypeErrors};
